"""Refresh exact installer hashes/ownership from the current reviewed payload."""
from pathlib import Path
import hashlib
import json
import re
from release_privacy import require_clean

HERE = Path(__file__).resolve().parent
manifest = json.loads((HERE / 'release-manifest.json').read_text(encoding='utf-8'))
entries = manifest['files']
require_clean(HERE / 'candidate', HERE / 'release-manifest.json')
assert {file.relative_to(HERE / 'candidate').as_posix() for file in (HERE / 'candidate').rglob('*') if file.is_file()} == {entry['path'] for entry in entries}, 'Refresh the reviewed release-manifest.json before building changed payloads.'
lines = ['#include "release-privacy-check.iss"', '; Generated by generate_installer_files.py. Exact package ownership only.']
for index, entry in enumerate(entries):
    file = HERE / 'candidate' / entry['path']
    assert '..' not in Path(entry['path']).parts and not Path(entry['path']).is_absolute()
    assert file.stat().st_size == entry['size'] and file.stat().st_size < 2**31
    assert hashlib.file_digest(file.open('rb'), 'sha256').hexdigest() == entry['sha256'], 'Refresh the reviewed release-manifest.json before building changed payloads.'
    rel = entry['path'].replace('/', '\\')
    parent = str(Path(entry['path']).parent).replace('/', '\\')
    dest = '{app}' + ('\\' + parent if parent != '.' else '')
    flags = 'ignoreversion uninsneveruninstall' if rel == 'fusion-install.json' else 'ignoreversion'
    lines.append(f'Source: "candidate\\{rel}"; DestDir: "{dest}"; Hash: "{entry["sha256"]}"; Flags: {flags}; Check: NeedProgramFile({index}, \'{rel.replace(chr(39), chr(39)*2)}\', {entry["size"]}, \'{entry["sha256"]}\')')
lines += ['', '[Dirs]']
for directory in sorted(path.relative_to(HERE / 'candidate') for path in (HERE / 'candidate').rglob('*') if path.is_dir() and not any(path.iterdir())):
    lines.append('Name: "{app}\\' + str(directory) + '"')
lines += ['', '[UninstallDelete]', '; Exact program files only. Preserve the install marker and user data.']
for entry in entries:
    if entry['path'] != 'fusion-install.json':
        lines.append('Type: files; Name: "{app}\\' + entry['path'].replace('/', '\\') + '"')
directories = sorted({str(parent) for entry in entries for parent in Path(entry['path']).parents if str(parent) != '.'}, key=lambda value: (-value.count('\\'), value))
lines += ['Type: dirifempty; Name: "{app}\\' + directory + '"' for directory in directories]
(HERE / 'installer-files.iss').write_text('\n'.join(lines) + '\n', encoding='utf-8-sig')
code_path = HERE / 'installer-file-checks.iss'
code = code_path.read_text(encoding='utf-8-sig')
code, count = re.subn(r'SetArrayLength\(ProgramFileDecisions, [1-9]\d*\);', f'SetArrayLength(ProgramFileDecisions, {len(entries)});', code)
assert count == 1
code_path.write_text(code, encoding='utf-8-sig')
print(f'Verified and generated metadata for {len(entries)} program files.')
